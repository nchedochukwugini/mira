export type ResearchEvent = { title: string; summary: string; entities: string[]; topics: string[]; status: "developing" | "ongoing" | "awaiting-decision" | "resolved" | "disputed" | "stale" | "unknown"; firstObservedAt: string | null; lastUpdatedAt: string; confidence: "high" | "medium" | "low"; evidenceIds: string[]; marketIds: string[]; timeline: EventTimelineEntry[] };
